AA_MAP = {
    "ALA":"A","ARG":"R","ASN":"N","ASP":"D","CYS":"C","GLN":"Q","GLU":"E",
    "GLY":"G","HIS":"H","ILE":"I","LEU":"L","LYS":"K","MET":"M","PHE":"F",
    "PRO":"P","SER":"S","THR":"T","TRP":"W","TYR":"Y","VAL":"V"
}

def extract_seq_from_pdb(pdb_path, chain_id):
    parser = PDB.PDBParser(QUIET=True)
    structure = parser.get_structure("x", pdb_path)
    seq = ""
    for chain in structure[0]:
        if chain.id == chain_id:
            for res in chain:
                if res.get_resname() in AA_MAP:
                    seq += AA_MAP[res.get_resname()]
    return seq

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--target", required=True)
    parser.add_argument("--pdb_dir", required=True)
    parser.add_argument("--output_dir", required=True)
    parser.add_argument("--binder_chain", default="H")
    args = parser.parse_args()

    target_seq = TARGET_SEQS[args.target]
    os.makedirs(args.output_dir, exist_ok=True)

    pdbs = [f for f in os.listdir(args.pdb_dir) if f.endswith(".pdb")]
    print(f"  {len(pdbs)} PDB trouvés")

    n_written = 0
    for pdb_file in sorted(pdbs):
        pdb_path = os.path.join(args.pdb_dir, pdb_file)
        binder_seq = extract_seq_from_pdb(pdb_path, args.binder_chain)
        if len(binder_seq) < 30:
            continue
        name = pdb_file.replace(".pdb", "")
        fasta_path = os.path.join(args.output_dir, f"{name}.fasta")
        with open(fasta_path, "w") as f:
            f.write(f">{name}\n{binder_seq}:{target_seq}\n")
        n_written += 1

    print(f"  {n_written} FASTA écrits → {args.output_dir}")

if __name__ == "__main__":
    main()
