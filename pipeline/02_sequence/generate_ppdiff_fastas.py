def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--target", required=True)
    parser.add_argument("--ppdiff_dir", required=True)
    parser.add_argument("--output_dir", required=True)
    args = parser.parse_args()

    target_seq = TARGET_SEQS[args.target]
    os.makedirs(args.output_dir, exist_ok=True)
    # Purge des anciens FASTA (évite l'accumulation de runs précédents -> 901 au lieu de 801)
    for _old in glob.glob(os.path.join(args.output_dir, "*.fasta")):
        os.remove(_old)

    # Lire toutes les séquences des 3 runs
    all_seqs = []
    for run in [1, 2, 3]:
        gen_file = os.path.join(args.ppdiff_dir, f"{args.target}_run{run}", "binder.gen.txt")
        if not os.path.exists(gen_file):
            # Essayer le format avec 1 à la fin
            gen_file = os.path.join(args.ppdiff_dir, f"{args.target}_run{run}1", "binder.gen.txt")
        if os.path.exists(gen_file):
            with open(gen_file) as f:
                seqs = [l.strip() for l in f if l.strip()]
                all_seqs.extend(seqs)
                print(f"  run{run}: {len(seqs)} séquences")
        else:
            print(f"  run{run}: fichier manquant ({gen_file})")

    print(f"  Total: {len(all_seqs)} séquences")

    # Écrire les FASTA
    n_written = 0
    for i, binder_seq in enumerate(all_seqs):
        # Enlever les G padding à la fin (dummy coords)
        binder_seq = binder_seq.rstrip("G")
        if len(binder_seq) < 30:
            continue
        name = f"{args.target}_ppdiff_{i+1:04d}"
        fasta_path = os.path.join(args.output_dir, f"{name}.fasta")
        with open(fasta_path, "w") as f:
            f.write(f">{name}\n{binder_seq}:{target_seq}\n")
        n_written += 1

    print(f"  {n_written} FASTA écrits → {args.output_dir}")

if __name__ == "__main__":
    main()
